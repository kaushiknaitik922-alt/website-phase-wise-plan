export async function getFlowers(): Promise<Flower[]> {
  return [...flowers].sort((a, b) => (a.sortOrder ?? 0) - (b.sortOrder ?? 0));
}

export async function getFeaturedFlowers(limit = 3): Promise<Flower[]> {
  const all = await getFlowers();
  return all.filter((f) => f.isFeatured).slice(0, limit);
}

